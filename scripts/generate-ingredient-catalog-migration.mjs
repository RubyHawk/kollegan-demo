#!/usr/bin/env node
// Generates the ingredient-catalog seed migration from prisma/seed-data/ingredient-catalog.mjs.
//
// Usage: node scripts/generate-ingredient-catalog-migration.mjs
//
// Emits prisma/migrations/20260613000002_ingredient_catalog/migration.sql with the
// table DDL plus an idempotent (ON CONFLICT DO NOTHING) seed of the global catalog.

import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { categories, ingredients } from '../prisma/seed-data/ingredients/index.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'prisma/migrations/20260613000002_ingredient_catalog');
const outFile = join(outDir, 'migration.sql');

function slugify(name) {
  return name
    .toLowerCase()
    .replaceAll('å', 'a').replaceAll('ä', 'a').replaceAll('ö', 'o')
    .replaceAll('é', 'e').replaceAll('è', 'e')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

function sqlStr(value) {
  return `'${String(value).replaceAll("'", "''")}'`;
}

function sqlArray(values) {
  if (!values || values.length === 0) return `ARRAY[]::text[]`;
  return `ARRAY[${values.map(sqlStr).join(', ')}]::text[]`;
}

const ddl = `-- Ingredient catalog: a shared reference library of ingredients.
-- Generated by scripts/generate-ingredient-catalog-migration.mjs — do not edit by hand.
-- Additive and idempotent: tables use IF NOT EXISTS and seeds use ON CONFLICT DO NOTHING.

CREATE TABLE IF NOT EXISTS "rst_ingredient_categories" (
  "id" TEXT NOT NULL,
  "name" TEXT NOT NULL,
  "emoji" TEXT,
  "sortOrder" INTEGER NOT NULL DEFAULT 0,
  "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT "rst_ingredient_categories_pkey" PRIMARY KEY ("id")
);

CREATE TABLE IF NOT EXISTS "rst_ingredients" (
  "id" TEXT NOT NULL DEFAULT (gen_random_uuid())::text,
  "organizationId" TEXT,
  "categoryId" TEXT NOT NULL,
  "slug" TEXT NOT NULL,
  "name" TEXT NOT NULL,
  "emoji" TEXT,
  "defaultUnit" TEXT,
  "aliases" TEXT[] NOT NULL DEFAULT ARRAY[]::text[],
  "allergens" TEXT[] NOT NULL DEFAULT ARRAY[]::text[],
  "isActive" BOOLEAN NOT NULL DEFAULT true,
  "createdBy" TEXT,
  "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "updatedAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "deletedAt" TIMESTAMP(3),
  CONSTRAINT "rst_ingredients_pkey" PRIMARY KEY ("id")
);

DO $$ BEGIN
  ALTER TABLE "rst_ingredients"
    ADD CONSTRAINT "rst_ingredients_categoryId_fkey"
    FOREIGN KEY ("categoryId") REFERENCES "rst_ingredient_categories"("id") ON DELETE RESTRICT ON UPDATE CASCADE;
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

DO $$ BEGIN
  ALTER TABLE "rst_ingredients"
    ADD CONSTRAINT "rst_ingredients_organizationId_fkey"
    FOREIGN KEY ("organizationId") REFERENCES "org_organizations"("id") ON DELETE CASCADE ON UPDATE CASCADE;
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

CREATE INDEX IF NOT EXISTS "rst_ingredients_categoryId_idx" ON "rst_ingredients"("categoryId");
CREATE INDEX IF NOT EXISTS "rst_ingredients_organizationId_idx" ON "rst_ingredients"("organizationId");
CREATE INDEX IF NOT EXISTS "rst_ingredients_name_idx" ON "rst_ingredients"("name");

-- One global ingredient per slug; tenants may keep their own slug namespace.
CREATE UNIQUE INDEX IF NOT EXISTS "rst_ingredients_global_slug_key"
  ON "rst_ingredients"("slug") WHERE "organizationId" IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS "rst_ingredients_org_slug_key"
  ON "rst_ingredients"("organizationId", "slug") WHERE "organizationId" IS NOT NULL;
`;

const categoryRows = categories
  .map((category) => `  (${sqlStr(category.id)}, ${sqlStr(category.name)}, ${sqlStr(category.emoji)}, ${category.sortOrder})`)
  .join(',\n');

const categorySeed = `
INSERT INTO "rst_ingredient_categories" ("id", "name", "emoji", "sortOrder") VALUES
${categoryRows}
ON CONFLICT ("id") DO NOTHING;
`;

const categoryEmoji = new Map(categories.map((category) => [category.id, category.emoji]));
const ingredientValues = [];
const seenSlugs = new Set();
for (const [categoryId, items] of Object.entries(ingredients)) {
  if (!categoryEmoji.has(categoryId)) {
    throw new Error(`Ingredient group "${categoryId}" has no matching category`);
  }
  for (const [name, emoji = '', unit = '', aliases = [], allergens = []] of items) {
    const slug = slugify(name);
    if (!slug) throw new Error(`Empty slug for ingredient "${name}"`);
    if (seenSlugs.has(slug)) {
      throw new Error(`Duplicate ingredient slug "${slug}" (${name})`);
    }
    seenSlugs.add(slug);
    // Emoji falls back to the category emoji so the long tail stays one-tap to add.
    const resolvedEmoji = (emoji && emoji.trim()) || categoryEmoji.get(categoryId) || '🍽️';
    const unitSql = unit && String(unit).trim() ? sqlStr(String(unit).trim()) : 'NULL';
    ingredientValues.push(
      `  (${sqlStr(categoryId)}, ${sqlStr(slug)}, ${sqlStr(name)}, ${sqlStr(resolvedEmoji)}, ${unitSql}, ${sqlArray(aliases)}, ${sqlArray(allergens)})`,
    );
  }
}

const ingredientSeed = `
INSERT INTO "rst_ingredients" ("categoryId", "slug", "name", "emoji", "defaultUnit", "aliases", "allergens") VALUES
${ingredientValues.join(',\n')}
ON CONFLICT ("slug") WHERE "organizationId" IS NULL DO NOTHING;
`;

mkdirSync(outDir, { recursive: true });
writeFileSync(outFile, `${ddl}${categorySeed}${ingredientSeed}`, 'utf8');
console.log(`Wrote ${outFile}`);
console.log(`Categories: ${categories.length}, ingredients: ${ingredientValues.length}`);
